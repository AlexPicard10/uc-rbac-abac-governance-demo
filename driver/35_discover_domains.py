"""35 · Unity Catalog "Discover" domains + Pages (Beta). Idempotent.

Creates an "Energy Operations" parent domain with two subdomains
(Renewable Generation, District Heating), assigns the demo schemas/tables as
assets (the shared country_reference table belongs to BOTH subdomains), and
publishes business-rule Pages on each domain.

Permissions by role are inherited from Unity Catalog: Discover shows each user
only the assets they can access (BROWSE/VIEW/SELECT), and a published Page is
readable by anyone who can access its domain. We set those UC grants per role in
governance (20); domain/page management is UI-only, so nothing extra to grant here.

Run AFTER governance (tables + grants must exist). Run: python driver/35_discover_domains.py
"""
from __future__ import annotations
import sys, uuid
import _common as C
from databricks.sdk.service.sql import StatementState
from databricks.sdk.service.domains import Domain, DomainIcon, DomainIconName

ICONS = {C.DOMAIN_PARENT_TAG: ("PLANET", "#1B3139"),
         C.DOMAIN_GEN_TAG: ("PLANT", "#00A972"),
         C.DOMAIN_HEAT_TAG: ("CITY", "#FFAB00")}
META = {
    C.DOMAIN_PARENT_TAG: ("Synthetic energy domains (governed by UC RBAC + ABAC)",
        "Business area grouping the company's renewable generation and district-heating data. "
        "Synthetic data; access governed by Unity Catalog RBAC + ABAC."),
    C.DOMAIN_GEN_TAG: ("Generation sites, output (MWh) & availability",
        "Renewable generation operations (Domain 1): sites/assets, country, daily generation and availability."),
    C.DOMAIN_HEAT_TAG: ("Anonymized district-heating consumption (MWh)",
        "District-heating energy consumption (Domain 2): anonymized customer segment, country, month."),
}
# domain tag_key -> list of (display_name, description, synonyms, body_markdown)
PAGES = {
    C.DOMAIN_PARENT_TAG: [(
        "Geo access rule — cross-domain sees FR + BE only",
        "Business rule: the cross-domain role is limited to France (FR) and Belgium (BE) across both domains.",
        ["geo restriction", "country filter", "cross-domain countries"],
        "## Rule\nA user acting as **role_cross_domain** can query **both** domains but sees "
        "**only rows for the countries in its entitlement — `FR` and `BE`**. Domain-specific roles "
        "(**role_generation**, **role_heating**) see **all countries** within their single "
        "permitted domain.\n\n"
        "## How it is enforced\nA Unity Catalog **ABAC row-filter policy** (`country_row_filter`) "
        "bound by the governed tag **`country`** on `country_code`. The filter evaluates the "
        "**active role** via `session_user()` against the entitlement table `gov.role_country_entitlements` "
        "— not group membership. To change which countries a role sees, add or remove a row in that "
        "table (no DDL).\n\n"
        "## Why\nCross-domain analysts get breadth (both domains) in exchange for a narrower geographic "
        "scope (FR + BE); domain teams keep a full geographic view of their own domain.")],
    C.DOMAIN_GEN_TAG: [(
        "Renewable generation metrics",
        "Business definitions for renewable generation operations (Domain 1).",
        ["generation", "availability", "MWh"],
        "## Definitions\n- **generation_mwh** — energy generated by a site on a given day (MWh).\n"
        "- **availability_pct** — percentage of the day the asset was available to generate (0–100).\n"
        "- **asset_type** — `wind` or `solar`.\n\n## Business rules\n"
        "- Availability below ~85% for a site is flagged for maintenance review (illustrative).\n"
        "- Reported per site per day; roll up to country via `country_code`.")],
    C.DOMAIN_HEAT_TAG: [(
        "District-heating consumption metrics",
        "Business definitions for district-heating consumption (Domain 2).",
        ["heating", "consumption", "segment"],
        "## Definitions\n- **consumption_mwh** — district-heating energy delivered to a customer segment "
        "in a country for a month (MWh).\n- **customer_segment** — anonymized: `Residential`, `Commercial`, "
        "or `Industrial`.\n\n## Business rules\n- Segments are anonymized; no individual customer is identifiable.\n"
        "- Reported monthly per segment per country.")],
}


def run(w, wid, sql):
    r = w.statement_execution.execute_statement(warehouse_id=wid, statement=sql, wait_timeout="50s")
    ok = r.status.state == StatementState.SUCCEEDED
    return ok, ("" if ok else (r.status.error.message if r.status.error else str(r.status.state)))


def main() -> int:
    w = C.ws(); wid = C.warehouse_id(w); me = int(w.current_user.me().id)

    # 1) Governed tags backing the domains
    for key in C.DOMAIN_TAGS:
        ok, err = run(w, wid, f"CREATE GOVERNED TAG `{key}`")
        print(("tag OK  " if ok else ("tag SKIP" if "already exists" in err.lower() else "tag ERR ")), key,
              "" if ok or "already exists" in err.lower() else err[:80])

    # 2) Domains (parent, then subdomains)
    ids = {d.tag_key: d.domain_id for d in w.domains.list_domains()}

    def ensure(key, parent=None):
        if key in ids:
            print("domain exists:", key); return ids[key]
        icon = DomainIcon(name=getattr(DomainIconName, ICONS[key][0]), color=ICONS[key][1])
        sub, desc = META[key]
        d = w.domains.create_domain(domain=Domain(tag_key=key, subtitle=sub, description=desc,
            icon=icon, parent_domain_id=parent, business_owner_ids=[me], technical_owner_ids=[me]))
        ids[key] = d.domain_id; print("domain created:", key, "->", d.domain_id); return d.domain_id

    pid = ensure(C.DOMAIN_PARENT_TAG)
    ensure(C.DOMAIN_GEN_TAG, parent=pid)
    ensure(C.DOMAIN_HEAT_TAG, parent=pid)

    # 3) Single-domain assets (empty value = membership)
    for tag, assets in C.DOMAIN_ASSETS.items():
        for kind, name in assets:
            ok, err = run(w, wid, f"ALTER {kind} {C.CATALOG}.{name} SET TAGS ('{tag}' = '')")
            print(("asset OK  " if ok else "asset ERR "), f"{kind} {name}", "" if ok else "-> " + err[:100])
    # 3b) Shared table belongs to BOTH subdomains (one statement = both tags)
    ok, err = run(w, wid, f"ALTER TABLE {C.CATALOG}.{C.SHARED_TABLE} "
                           f"SET TAGS ('{C.DOMAIN_GEN_TAG}' = '', '{C.DOMAIN_HEAT_TAG}' = '')")
    print(("shared OK " if ok else "shared ERR"), C.SHARED_TABLE, "(both subdomains)", "" if ok else "-> " + err[:100])

    # 4) Pages (published). Idempotent via the server's unique-name check: a repeat
    #    create raises "already exists" -> skip. DRAFT fallback ONLY for a publish-
    #    permission error (never on already-exists, which would make a duplicate).
    for tag, pages in PAGES.items():
        dom = f"domains/{ids[tag]}"
        for title, desc, syn, body in pages:
            payload = {"domain": dom, "display_name": title, "description": desc, "synonyms": syn,
                       "body": body, "state": "PUBLISHED", "owner_ids": [me]}
            try:
                w.api_client.do("POST", "/api/2.0/knowledge/pages",
                                query={"request_id": str(uuid.uuid4())}, body=payload)
                print("page created:", title)
            except Exception as e:
                msg = str(e).lower()
                if "already exists" in msg:
                    print("page exists:", title)
                elif any(k in msg for k in ("permission", "not allowed", "forbidden", "manage")):
                    payload["state"] = "DRAFT"
                    w.api_client.do("POST", "/api/2.0/knowledge/pages",
                                    query={"request_id": str(uuid.uuid4())}, body=payload)
                    print("page created (DRAFT — no publish permission):", title)
                else:
                    raise

    print("\nDISCOVER DOMAINS + PAGES: done. Open Discover -> Browse by domain / Pages.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
